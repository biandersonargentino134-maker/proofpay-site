function ppTranslate(lang) {
  const dict = PP_TRANSLATIONS[lang] || PP_TRANSLATIONS.pt;

  document.documentElement.lang = lang === 'en' ? 'en' : 'pt-BR';

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) el.textContent = dict[key];
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) el.placeholder = dict[key];
  });

  document.querySelectorAll('.lang-btn').forEach((btn) => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });

  localStorage.setItem('proofpay-lang', lang);

  // Avisa qualquer JS que precise re-renderizar texto dinâmico (ex.: status
  // de carteira, mensagens geradas por script) que o idioma mudou.
  document.dispatchEvent(new CustomEvent('pp:langchange', { detail: { lang } }));
}

function ppSetLanguage(lang) {
  ppTranslate(lang);
}

function ppCurrentLang() {
  return localStorage.getItem('proofpay-lang') || 'pt';
}

function ppT(key) {
  const dict = PP_TRANSLATIONS[ppCurrentLang()] || PP_TRANSLATIONS.pt;
  return dict[key] || key;
}

document.addEventListener('DOMContentLoaded', () => {
  ppTranslate(ppCurrentLang());
});
